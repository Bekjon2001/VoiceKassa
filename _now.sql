\echo === LATEST 10 ORDERS (all statuses) ===
SELECT "ID","BUSINESS_ID","TABLE_ID","STATUS","TOTAL_AMOUNT","CREATED_AT"
FROM voicekassa."ORDERS" ORDER BY "ID" DESC LIMIT 10;

\echo === OPEN ORDERS COUNT PER BUSINESS ===
SELECT "BUSINESS_ID", COUNT(*) AS open_cnt
FROM voicekassa."ORDERS" WHERE "STATUS" IN (0,1)
GROUP BY "BUSINESS_ID" ORDER BY "BUSINESS_ID";

\echo === ORDER_ITEMS for latest order ===
SELECT oi."ID", oi."ORDER_ID", oi."PRODUCT_ID", oi."PRODUCT_NAME_SPOKEN", oi."QUANTITY"
FROM voicekassa."ORDER_ITEMS" oi ORDER BY oi."ORDER_ID" DESC LIMIT 20;
