\echo ==== BARCHA "Anor" BIZNESLAR (faol va nofaol) ====
SELECT "ID", "NAME", "TYPE", "IS_ACTIVE" FROM voicekassa."BUSINESSES" WHERE "NAME" ILIKE '%Anor%' ORDER BY "ID";

\echo ==== BARCHA RESTORAN EGALARI (owner) ====
SELECT "BUSINESS_ID", "LOGIN", "FULL_NAME", "IS_ACTIVE", "SUBSCRIPTION_ENDS_AT" FROM voicekassa."RESTAURANT_OWNERS" ORDER BY "BUSINESS_ID";

\echo ==== OXIRGI 10 BUYURTMA ====
SELECT o."ID", o."BUSINESS_ID", b."NAME" AS biz, o."TABLE_ID", o."STATUS", o."TOTAL_AMOUNT", o."CREATED_AT"
FROM voicekassa."ORDERS" o LEFT JOIN voicekassa."BUSINESSES" b ON b."ID"=o."BUSINESS_ID"
ORDER BY o."ID" DESC LIMIT 10;

\echo ==== HAR BIZNESDAGI OCHIQ (status 0/1) BUYURTMALAR SONI ====
SELECT o."BUSINESS_ID", b."NAME" AS biz, COUNT(*) FILTER (WHERE o."STATUS" IN (0,1)) AS open_cnt
FROM voicekassa."ORDERS" o LEFT JOIN voicekassa."BUSINESSES" b ON b."ID"=o."BUSINESS_ID"
GROUP BY o."BUSINESS_ID", b."NAME" ORDER BY o."BUSINESS_ID";
