ALTER TABLE voicekassa."STAFF"
    ADD COLUMN IF NOT EXISTS "LOGIN" varchar(100),
    ADD COLUMN IF NOT EXISTS "PASSWORD_HASH" varchar(500),
    ADD COLUMN IF NOT EXISTS "ACCESS_TOKEN" varchar(200);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_STAFF_LOGIN"
    ON voicekassa."STAFF" ("LOGIN")
    WHERE "LOGIN" IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS "IX_STAFF_ACCESS_TOKEN"
    ON voicekassa."STAFF" ("ACCESS_TOKEN")
    WHERE "ACCESS_TOKEN" IS NOT NULL;
